function entry(id, productFamily, handing, recovery, manufacturerArticle, relativePath, sha256) {
  return { id, productFamily, handing, recovery, manufacturerArticle, relativePath, sha256 };
}

function verifySource(source, expected, path) {
  const checks = [
    [/FILE_SCHEMA\(\('IFC4'\)\)/, "IFC4 schema"],
    [/CoordinationView_V2\.0/, "CoordinationView_V2.0"],
    [/IFCSIUNIT\(\*,\.LENGTHUNIT\.,\.MILLI\.,\.METRE\.\)/, "declared millimetre length unit"],
    [new RegExp(`IFCTEXT\\('${expected.manufacturerArticle}'\\)`), `manufacturer article ${expected.manufacturerArticle}`],
    [new RegExp(expected.productFamily.replace(" ", "[_ ]")), expected.productFamily],
  ];
  for (const [pattern, label] of checks) if (!pattern.test(source)) throw new Error(`${basename(path)} does not contain expected ${label}`);
  const ports = (source.match(/=IFCDISTRIBUTIONPORT\(/g) ?? []).length;
  if (ports !== 7) throw new Error(`${basename(path)} has ${ports} distribution ports; expected the reviewed count of 7`);
}

function parseIfc(source, expected) {
  const entities = new Map();
  for (const match of source.matchAll(/^#(\d+)=([A-Z0-9_]+)\((.*)\);\r?$/gm)) {
    entities.set(Number(match[1]), { type: match[2], args: match[3] });
  }
  const styleByItem = new Map();
  for (const entity of entities.values()) {
    if (entity.type !== "IFCSTYLEDITEM") continue;
    const args = splitTopLevel(entity.args);
    const item = firstRef(args[0]);
    const style = firstRef(args[1]);
    if (item && style) styleByItem.set(item, colourForStyle(style, entities));
  }
  const meshSets = [];
  const allPoints = [];
  let faceCount = 0;
  for (const [id, entity] of entities) {
    if (entity.type !== "IFCPOLYGONALFACESET") continue;
    const args = splitTopLevel(entity.args);
    const pointEntity = entities.get(firstRef(args[0]));
    if (pointEntity?.type !== "IFCCARTESIANPOINTLIST3D") throw new Error(`Polygonal face set #${id} has no 3D point list`);
    const sourcePoints = [...pointEntity.args.matchAll(/\(([-+\d.Ee]+),([-+\d.Ee]+),([-+\d.Ee]+)\)/g)]
      .map((match) => [Number(match[1]), Number(match[2]), Number(match[3])]);
    const points = sourcePoints.map(([x, y, z]) => [quantize(x), quantize(-(y + 295)), quantize(z)]);
    const faces = allRefs(args[2]).map((faceId) => {
      const face = entities.get(faceId);
      if (!face || !["IFCINDEXEDPOLYGONALFACE", "IFCINDEXEDPOLYGONALFACEWITHVOIDS"].includes(face.type)) throw new Error(`Unsupported face #${faceId}`);
      return [...splitTopLevel(face.args)[0].matchAll(/\d+/g)].map((match) => Number(match[0]) - 1);
    });
    allPoints.push(...points);
    faceCount += faces.length;
    meshSets.push({ colour: styleByItem.get(id) ?? "#aeb6b9", points, faces });
  }
  if (meshSets.length !== 20 || faceCount < 2500) throw new Error(`Reviewed mesh expectation failed: ${meshSets.length} sets / ${faceCount} faces`);
  const distributionPorts = parseDistributionPorts(entities);
  verifyReviewedDuctPorts(distributionPorts, expected.handing);
  return {
    meshSets,
    faceCount,
    distributionPortCount: distributionPorts.length,
    distributionPorts,
    boundsMm: {
      min: [0, 1, 2].map((axis) => Math.min(...allPoints.map((point) => point[axis]))),
      max: [0, 1, 2].map((axis) => Math.max(...allPoints.map((point) => point[axis]))),
    },
  };
}

function parseDistributionPorts(entities) {
  const ports = [];
  for (const entity of entities.values()) {
    if (entity.type !== "IFCDISTRIBUTIONPORT") continue;
    const args = splitTopLevel(entity.args);
    const placement = entities.get(firstRef(args[5]));
    const axisPlacement = placement?.type === "IFCLOCALPLACEMENT" ? entities.get(allRefs(placement.args)[1]) : null;
    const point = axisPlacement?.type === "IFCAXIS2PLACEMENT3D" ? entities.get(firstRef(axisPlacement.args)) : null;
    const coordinates = point?.type === "IFCCARTESIANPOINT"
      ? String(point.args).replaceAll(/[()]/g, "").split(",").map(Number)
      : null;
    if (!coordinates || coordinates.length !== 3 || coordinates.some((value) => !Number.isFinite(value))) throw new Error("Distribution port placement could not be resolved");
    ports.push({
      name: unquote(args[2]),
      positionMm: [quantize(coordinates[0]), quantize(-(coordinates[1] + 295)), quantize(coordinates[2])],
      flowDirection: enumValue(args[7]),
      predefinedType: enumValue(args[8]),
      systemType: enumValue(args[9]),
    });
  }
  return ports;
}

function verifyReviewedDuctPorts(ports, handing) {
  const ductPorts = ports.filter((port) => port.predefinedType === "DUCT");
  if (!ductPorts.every((port) => Math.abs(port.positionMm[2] - 850) < 0.1)) throw new Error("Duct connector Z changed from the reviewed 850 mm top setout");
  const actual = ductPorts
    .map((port) => `${port.positionMm.slice(0, 2).join(",")}|${port.flowDirection}|${port.systemType}`).sort();
  const expected = (handing === "L" ? [
      "-290,-162|SINK|VENTILATION",
      "-290,118.5|SOURCE|VENTILATION",
      "290,-162|SOURCE|EXHAUST",
      "290,118.5|SINK|VENTILATION",
    ] : [
      "-290,-162|SINK|VENTILATION",
      "-290,118.5|SOURCE|EXHAUST",
      "290,-162|SOURCE|VENTILATION",
      "290,118.5|SINK|VENTILATION",
    ]).sort();
  if (JSON.stringify(expected) !== JSON.stringify(actual)) {
    throw new Error(`Duct connector set changed: ${actual.join("; ")}`);
  }
}

function colourForStyle(styleId, entities) {
  const queue = [styleId], seen = new Set();
  while (queue.length) {
    const id = queue.shift();
    if (seen.has(id)) continue;
    seen.add(id);
    const entity = entities.get(id);
    if (!entity) continue;
    if (entity.type === "IFCCOLOURRGB") {
      const values = splitTopLevel(entity.args).slice(-3).map(Number);
      return `#${values.map((value) => Math.max(0, Math.min(255, Math.round(value * 255))).toString(16).padStart(2, "0")).join("")}`;
    }
    queue.push(...allRefs(entity.args));
  }
  return "#aeb6b9";
}

function splitTopLevel(source) {
  const values = [];
  let depth = 0, start = 0, quote = false;
  for (let index = 0; index < source.length; index += 1) {
    const character = source[index];
    if (character === "'") quote = !quote;
    else if (!quote) {
      if (character === "(") depth += 1;
      else if (character === ")") depth -= 1;
      else if (character === "," && depth === 0) {
        values.push(source.slice(start, index));
        start = index + 1;
      }
    }
  }
  values.push(source.slice(start));
  return values;
}
function allRefs(source) { return [...String(source).matchAll(/#(\d+)/g)].map((match) => Number(match[1])); }
function firstRef(source) { return allRefs(source)[0] ?? null; }
function quantize(value) { return Number(value.toFixed(3)); }
function enumValue(value) { return String(value).replaceAll(".", ""); }
function unquote(value) { return String(value).startsWith("'") ? String(value).slice(1, -1).replaceAll("''", "'") : String(value); }
